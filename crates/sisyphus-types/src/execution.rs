#[derive(Serialize, Deserialize, Clone, Debug)]
pub enum ExecutionEvent {
    NodeStarted {
        node_name: String,
    },
    NodeCompleted {
        node_name: String,
        output: NodeOutput,
        fuel_consumed: i64,
        duration_ms: i64,
    },
    NodeFailed {
        node_name: String,
        error: String,
        fuel_consumed: i64,
        duration_ms: i64,
    },
    ExecutionComplete {
        result: NodeOutput,
    },
    /// A machine-executable plan generated by the cognitive engine for an external agent (e.g., jcode).
    CognitivePlan {
        plan: CognitivePlan,
    },
    /// A status update from the cognitive loop (e.g., "Predicting", "Reflecting", "Critiquing").
    CognitiveStep {
        step: String,
        message: String,
        metrics: Option<CognitiveMetrics>,
    },
    /// A real-time micro-reflection result for a single node execution.
    MicroReflection {
        node_name: String,
        prediction: String,
        actual: String,
        decision: String,
        updates: Option<HashMap<String, Value>>,
        reason: Option<String>,
    },
    /// The cognitive loop has converged and completed.
    CognitiveComplete {
        report: String,
    },
}

/// A machine-executable plan generated by the cognitive engine for an external agent (e.g., jcode).
