#[async_trait]
pub trait StateStore: Send + Sync {
    async fn get_state_json(&self, key: &str) -> Result<Option<serde_json::Value>, TypesError>;
    async fn set_state_json(&self, key: &str, value: serde_json::Value) -> Result<(), TypesError>;

    async fn get(&self, key: &str) -> Result<Option<Vec<u8>>, TypesError>;
    async fn set(&self, key: &str, value: &[u8]) -> Result<(), TypesError>;

    async fn get_traces_for_sop(&self, sop_id: &str) -> Result<Vec<(String, String, String, i64, i64)>, TypesError>;
}

/// Strongly-typed wrapper around `serde_json::Value` for SOP node outputs.
/// Provides type safety and prevents accidental mixing with raw JSON values.
#[derive(Serialize, Deserialize, Clone, Debug)]
pub struct NodeOutput(pub Value);

impl NodeOutput {
    pub fn into_inner(self) -> Value {
        self.0
    }
}

impl Default for NodeOutput {
    fn default() -> Self {
        NodeOutput(Value::Null)
    }
}

impl From<Value> for NodeOutput {
    fn from(v: Value) -> Self {
        NodeOutput(v)
    }
}

impl std::ops::Deref for NodeOutput {
    type Target = Value;
    fn deref(&self) -> &Value {
        &self.0
    }
}

impl std::fmt::Display for NodeOutput {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        self.0.fmt(f)
    }
}

#[derive(Clone, Serialize, Deserialize, Debug)]
pub enum SupervisorDecision {
    Continue { deviation: f64 },
    Pivot {
        reason: String,
        suggested_correction: Option<crate::graph::SOPGraphConfig>,
    },
}

#[async_trait]
pub trait RuntimeSupervisor: Send + Sync {
    async fn evaluate(
        &self,
        node_name: &str,
        output: &NodeOutput,
        ctx: Arc<ExecutionContext>,
    ) -> Result<SupervisorDecision, String>;
}

impl PartialEq<Value> for NodeOutput {
    fn eq(&self, other: &Value) -> bool {
        self.0 == *other
    }
}

impl PartialEq<NodeOutput> for Value {
    fn eq(&self, other: &NodeOutput) -> bool {
        self == &other.0
    }
}

impl PartialEq for NodeOutput {
    fn eq(&self, other: &Self) -> bool {
        self.0 == other.0
    }
}

#[derive(Serialize, Deserialize, Clone, Debug)]
