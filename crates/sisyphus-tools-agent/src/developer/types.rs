//! Shared types for the Developer module.
//!
//! This module defines the data models used by the development agent:
//! actions, verification methods, status tracking, plans, checkpoints, and reports.

use serde::{Deserialize, Serialize};

/// What action to perform in a development step
#[derive(Debug, Clone, Serialize, Deserialize)]
#[serde(tag = "type", content = "params")]
pub enum DevAction {
    /// Create a new file
    CreateFile { path: String, content: String },
    /// Edit an existing file (replace old_string with new_string)
    EditFile {
        path: String,
        old_string: String,
        new_string: String,
    },
    /// Run a shell command in a directory
    RunCommand {
        command: String,
        dir: Option<String>,
    },
    /// Read a file for analysis
    ReadFile { path: String },
    /// Multiple granular edits described in natural language — LLM will decompose
    ComplexChange { description: String },
}

/// How to verify a step succeeded
#[derive(Debug, Clone, Serialize, Deserialize)]
#[serde(tag = "type", content = "params")]
pub enum VerificationMethod {
    CargoCheck,
    CargoTest,
    LspDiagnostics { path: String },
    Command { command: String },
    LlmReview { criteria: String },
    None,
}

#[derive(Debug, Clone, Serialize, Deserialize, PartialEq, Eq)]
/// Step Status.
pub enum StepStatus {
    Pending,
    InProgress,
    Success,
    Failed(String),
    Skipped,
}

/// A single step in a development plan
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct DevStep {
    pub id: usize,
    pub description: String,
    pub action: DevAction,
    pub expected_outcome: String,
    pub verification: VerificationMethod,
    pub status: StepStatus,
}

/// A structured development plan generated by LLM
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct DevelopmentPlan {
    pub goal: String,
    pub overview: String,
    pub steps: Vec<DevStep>,
}

/// Result of executing a single step
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct StepResult {
    pub step_id: usize,
    pub status: StepStatus,
    pub output: String,
    pub verification_output: Option<String>,
}

/// Overall development result
#[derive(Debug, Clone, PartialEq)]
pub enum DevOverallStatus {
    Success,
    PartialFailure {
        completed: usize,
        total: usize,
    },
    Failed(String),
    /// 用户中断（T2.1 MVP）：中断前已完成的步骤结果已落 checkpoint，
    /// 调用方可用 resume 恢复未完成步骤。
    Cancelled,
}

/// 客观验收门（`dev --verify-cmd`）的结果。
///
/// 步骤自带的 `verification` 是**模型自选**的，可能与用户目标不一致：例如目标是
/// 「clippy -D warnings 通过」，模型却声明 `CargoCheck`（警告不是错误 → 通过），
/// 于是「全部步骤成功」而目标其实没达成。最终闸门由用户指定命令，是唯一的
/// 「成功」判据。
#[derive(Debug, Clone, PartialEq)]
pub struct FinalVerification {
    /// 用户给定的验收命令。
    pub command: String,
    /// 最后一次运行是否通过。
    pub passed: bool,
    /// 已消耗的自动修复尝试次数（0 表示一次就过）。
    pub fix_attempts: usize,
    /// 最后一次运行的合并输出（stdout+stderr，已截断）。
    pub output: String,
}

/// Full development report
#[derive(Debug, Clone)]
pub struct DevelopmentReport {
    pub goal: String,
    pub overall_status: DevOverallStatus,
    pub steps: Vec<StepResult>,
    pub artifacts: Vec<String>,
    /// 客观验收门结果（未配置 `--verify-cmd` 时为 `None`）。
    pub final_verification: Option<FinalVerification>,
}

/// Checkpoint for resuming a development session after interruption.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct DevCheckpoint {
    pub goal: String,
    pub project_context: String,
    pub completed_step_ids: Vec<usize>,
    pub step_results: Vec<StepResult>,
    pub artifacts: Vec<String>,
}

#[derive(Serialize, Deserialize)]
pub(super) struct EditRequest {
    pub path: String,
    pub old_string: String,
    pub new_string: String,
}
