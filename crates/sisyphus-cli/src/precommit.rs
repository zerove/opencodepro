use anyhow::{Context, Result};
use std::path::PathBuf;

/// Resolve the git repo root from the given directory (or cwd).
fn resolve_repo(dir: Option<PathBuf>) -> Result<PathBuf> {
    let base = match dir {
        Some(p) => p,
        None => std::env::current_dir().context("Failed to get current directory")?,
    };
    let output = std::process::Command::new("git")
        .args(["rev-parse", "--show-toplevel"])
        .current_dir(&base)
        .output()
        .context("Failed to run git rev-parse — is git installed?")?;

    if !output.status.success() {
        let stderr = String::from_utf8_lossy(&output.stderr);
        anyhow::bail!("Not in a git repository: {}", stderr.trim());
    }

    let root = String::from_utf8_lossy(&output.stdout).trim().to_string();
    Ok(PathBuf::from(root))
}

pub fn run_install(
    dir: Option<PathBuf>,
    no_fmt: bool,
    no_lint: bool,
    allow_warnings: bool,
    lang: Option<String>,
) -> Result<()> {
    let backend = lang.unwrap_or_else(|| "rust".to_string());
    let mut cfg = sisyphus_tools::PrecommitConfig {
        backend,
        ..Default::default()
    };
    if no_fmt {
        cfg.check_fmt = false;
    }
    if no_lint {
        cfg.check_lint = false;
    }
    if allow_warnings {
        cfg.lint_deny_warnings = false;
    }

    let repo = resolve_repo(dir)?;
    sisyphus_tools::install_precommit(&repo, &cfg)?;

    println!(
        "✅ Pre-commit hook installed at {}/.git/hooks/pre-commit",
        repo.display()
    );
    println!("   Backend: {}", cfg.backend);
    println!("   Checks enabled:");
    println!(
        "   - Format check: {}",
        if cfg.check_fmt { "yes" } else { "no" }
    );
    println!(
        "   - Lint: {}",
        if cfg.check_lint {
            if cfg.lint_deny_warnings {
                "yes (deny warnings)"
            } else {
                "yes"
            }
        } else {
            "no"
        }
    );
    Ok(())
}

pub fn run_uninstall(dir: Option<PathBuf>) -> Result<()> {
    let repo = resolve_repo(dir)?;
    sisyphus_tools::uninstall_precommit(&repo)?;
    println!(
        "✅ Pre-commit hook removed from {}/.git/hooks/pre-commit",
        repo.display()
    );
    Ok(())
}

pub fn run_status(dir: Option<PathBuf>) -> Result<()> {
    let repo = resolve_repo(dir)?;
    let hooks_dir = repo.join(".git/hooks");
    let hook_path = hooks_dir.join("pre-commit");

    if hook_path.exists() {
        let is_sisyphus = sisyphus_tools::is_sisyphus_hook(&repo);
        let source = if is_sisyphus {
            "Sisyphus"
        } else {
            "unknown (not generated by Sisyphus)"
        };
        println!("Pre-commit hook: INSTALLED");
        println!("  Path: {}", hook_path.display());
        println!("  Source: {source}");

        if is_sisyphus {
            if let Some(content) = sisyphus_tools::read_precommit(&repo) {
                println!("\n--- Content ---");
                println!("{content}");
            }
        }
    } else {
        println!("Pre-commit hook: NOT INSTALLED");
        println!("  Install with: sisyphus precommit install");
    }
    Ok(())
}
