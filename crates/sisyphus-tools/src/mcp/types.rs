pub const MCP_ERROR_INVALID_PARAMS: i64 = -32602;
pub const MCP_ERROR_INTERNAL: i64 = -32603;

pub const MCP_ERROR_TOOL_NOT_FOUND: i64 = -32000;
pub const MCP_ERROR_TOOL_EXECUTION: i64 = -32001;
