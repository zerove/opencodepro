#!/usr/bin/env python3
"""校验 Dockerfile 的「依赖缓存层」与 workspace 成员保持一致。

背景（两次真实失败，本地都不复现）：

**一、`.dockerignore` 把 workspace 成员排掉**

`.dockerignore` 曾写着 `evals/`（注释是「Evaluation data」）。`evals` 是
workspace 成员，于是镜像里 `cargo build -p sisyphus-bridge` 直接失败：

    error: failed to load manifest for workspace member `/app/evals`
    Caused by: failed to read `/app/evals/Cargo.toml`

哪怕桥接根本不依赖 evals —— cargo 加载 workspace 时必须能读到**每个**成员的
manifest。多架构镜像发布因此从未成功过。

**二、手写的「manifest + 空壳源码」清单会烂掉，而 `|| true` 让它无声无息**

依赖缓存层的套路是：只 COPY 各成员 manifest、造空壳源码、先编译一次依赖，再
`COPY . .` 用真实代码覆盖。好处是外部依赖（wasmtime 之类）能进镜像层缓存。

问题是这份清单是**手抄**的：漏了 9 个成员，其中就有 `evals`。而那一行写的是

    RUN cargo build --release -p sisyphus-bridge 2>/dev/null || true

`|| true` 把「workspace 加载失败」吞成了成功，于是：

  * 该层**从未**缓存过任何依赖（每次都白跑）；
  * 上面第一个缺陷被同一行 `|| true` 掩盖了几个版本。

所以本脚本强制三件事：

1. workspace 的**每个**成员都在 Dockerfile 的 manifest COPY 块里；
2. 每个成员**显式声明 path** 的 target 文件都有对应的空壳（cargo 在解析
   manifest 阶段就会检查这些路径，缺了同样整体失败）；
3. `.dockerignore` 没有排除任何成员；依赖层里不允许出现 `|| true`。

`--fix` 会按当前 workspace 重新生成整块（标记之间），改完记得本地跑一次
`podman build`/`docker build` 验证。

用法：
    python3 scripts/audit_dockerfile.py           # 校验（CI）
    python3 scripts/audit_dockerfile.py --fix     # 按 workspace 重写该块
    python3 scripts/audit_dockerfile.py --self-check
"""

from __future__ import annotations

import fnmatch
import os
import sys

try:
    import tomllib
except ImportError:  # pragma: no cover - Python < 3.11
    tomllib = None

BEGIN = "# >>> deps-layer (generated by scripts/audit_dockerfile.py --fix) >>>"
END = "# <<< deps-layer <<<"

# 显式 path 只在这些表里才需要空壳。`[package] build` 单独处理。
TARGET_TABLES = ("bin", "lib", "example", "test", "bench")

# 没有写 path 时 cargo 用的默认路径模板。注意 `[[bench]] name = "x"` 这类
# **显式命名**的 target 即使不给 path 也必须有对应文件（cargo 报
# `can't find `x` bench at `benches/x.rs``)；只有完全没被提及的 target 才靠
# 自动发现，那才允许缺失。
DEFAULT_PATHS = {
    "bin": "src/bin/{name}.rs",
    "lib": "src/lib.rs",
    "example": "examples/{name}.rs",
    "test": "tests/{name}.rs",
    "bench": "benches/{name}.rs",
}

# 需要 `fn main() {}` 的 target 种类（空文件编译不过）。
NEEDS_MAIN = {"bin", "example", "bench", "custom-build"}


def workspace_members(root="."):
    """返回 workspace 成员目录（相对路径，规范化为 / 分隔），不含根包。"""
    path = os.path.join(root, "Cargo.toml")
    with open(path, "rb") as fh:
        doc = tomllib.load(fh)
    members = ((doc.get("workspace") or {}).get("members")) or []
    out = []
    for m in members:
        norm = m.strip().rstrip("/").replace("\\", "/")
        if norm and norm not in out:
            out.append(norm)
    return sorted(out)


def stub_targets(root, members):
    """收集需要造空壳的 target 路径 -> 内容。

    两类都要覆盖：

    * **显式写了 path 的** target —— cargo 解析 manifest 时就检查该文件是否存在
      （`can't find ... bin at ...`）；
    * **完全没声明 target 的成员** —— cargo 报 `no targets specified in the
      manifest, either src/lib.rs, src/main.rs, ... must be present`。所以每个
      成员至少要有 `src/lib.rs`（空壳 lib 不影响后面的真实构建，`COPY . .`
      会覆盖）。
    """
    need = {}
    for member in members:
        manifest = os.path.join(root, member, "Cargo.toml")
        if not os.path.isfile(manifest):
            continue
        with open(manifest, "rb") as fh:
            doc = tomllib.load(fh)
        package = doc.get("package") or {}
        build = package.get("build")
        if isinstance(build, str) and build.endswith(".rs"):
            need[f"{member}/{build}"] = "fn main() {}\n"
        for table in TARGET_TABLES:
            entries = doc.get(table)
            if isinstance(entries, dict):
                entries = [entries]
            for entry in entries or []:
                if not isinstance(entry, dict):
                    continue
                path = entry.get("path")
                if not isinstance(path, str) or not path.endswith(".rs"):
                    name = entry.get("name")
                    template = DEFAULT_PATHS.get(table)
                    if not isinstance(name, str) or not template:
                        continue
                    path = template.format(name=name)
                need[f"{member}/{path}"] = (
                    "fn main() {}\n" if table in NEEDS_MAIN else ""
                )
        # 兜底：没有任何 target 的成员会被 cargo 拒绝加载
        need.setdefault(f"{member}/src/lib.rs", "")
    return need


def render_block(members, stubs):
    lines = [BEGIN, ""]
    lines.append("# workspace 的**每个**成员 manifest 都必须在这里：cargo 加载 workspace")
    lines.append("# 时任何成员缺失都会整体失败（`error: failed to load manifest for")
    lines.append("# workspace member`），`-p sisyphus-bridge` 也不例外。")
    lines.append("COPY Cargo.toml Cargo.lock ./")
    for member in members:
        lines.append(f"COPY {member}/Cargo.toml {member}/")
    lines.append("")
    lines.append("# 显式声明了 path 的 target 文件同样必须在场，否则 cargo 连 metadata")
    lines.append("# 都不给（`can't find ... bin at ...`）。这里只造空壳，用来把**外部")
    lines.append("# 依赖**编进本层缓存；下一层 `COPY . .` 会用真实代码覆盖。")
    if stubs:
        cmds = []
        for path in sorted(stubs):
            parent = os.path.dirname(path)
            body = stubs[path].strip()
            cmd = f'mkdir -p {parent} && echo "{body}" > {path}'
            cmds.append(cmd)
        lines.append("RUN " + " && \\\n    ".join(cmds))
    else:
        lines.append("# （当前 workspace 没有显式 path 的 target，无需空壳）")
    lines.append("")
    lines.append("# 只编译依赖。空壳源码下这条命令**必须**成功：任何失败都说明本层")
    lines.append("# 配置写错了。这里一度写着 `2>/dev/null || true`——它把「workspace 加载")
    lines.append("# 失败」吞成成功，于是本层从未缓存过依赖，还顺带掩盖了 evals 被")
    lines.append("# .dockerignore 排掉的缺陷。不要加回任何形式的容错。")
    lines.append("RUN cargo build --release -p sisyphus-bridge")
    lines.append("")
    lines.append(END)
    return "\n".join(lines)


def replace_block(text, block):
    start = text.find(BEGIN)
    end = text.find(END)
    if start == -1 or end == -1 or end < start:
        return None
    return text[:start] + block + text[end + len(END):]


def dockerignore_excludes(patterns, member):
    """`.dockerignore` 是否排除了该成员目录。

    只做保守判定：命中多数情况下确实会排除。`!` 取反行会让判定失效，
    遇到时宁可不算排除（避免误报——误报会让人把这个门禁关掉，那才是灾难）。
    """
    member = member.strip("/")
    parts = member.split("/")
    hit = False
    for raw in patterns:
        pat = raw.strip()
        if not pat or pat.startswith("#"):
            continue
        negated = pat.startswith("!")
        if negated:
            hit = False
            continue
        pat = pat.rstrip("/")
        if not pat:
            continue
        if any(
            fnmatch.fnmatchcase(candidate, pat) for candidate in (member, parts[0])
        ):
            hit = not negated
    return hit


def check(root="."):
    problems = []
    dockerfile = os.path.join(root, "Dockerfile")
    if not os.path.isfile(dockerfile):
        return ["Dockerfile 不存在"]

    if tomllib is None:  # pragma: no cover
        return ["需要 Python 3.11+（tomllib）"]

    with open(dockerfile, encoding="utf-8") as fh:
        text = fh.read()

    members = workspace_members(root)
    if not members:
        return ["根 Cargo.toml 的 [workspace] members 为空：无法校验"]

    start = text.find(BEGIN)
    end = text.find(END)
    if start == -1 or end == -1:
        problems.append(
            "Dockerfile 缺少依赖层标记（%s / %s）：无法确认该层与 workspace 一致"
            % (BEGIN, END)
        )
        block = text
    else:
        block = text[start:end]

    for member in members:
        if f"COPY {member}/Cargo.toml" not in block:
            problems.append(
                "Dockerfile 依赖层缺少 %s/Cargo.toml：镜像里 cargo 会因"
                "「failed to load manifest for workspace member」整体失败"
                % member
            )

    for path in sorted(stub_targets(root, members)):
        if path not in block:
            problems.append(
                "Dockerfile 依赖层缺少空壳文件 %s（显式 path 的 target 或"
                "「没有任何 target 的成员」都会让 cargo 在解析阶段直接失败）" % path
            )

    ignored = []
    if os.path.isfile(os.path.join(root, ".dockerignore")):
        with open(os.path.join(root, ".dockerignore"), encoding="utf-8") as fh:
            ignored = fh.read().splitlines()
    for member in members:
        if dockerignore_excludes(ignored, member):
            problems.append(
                ".dockerignore 排除了 workspace 成员 %s：镜像里根本拿不到它的"
                " manifest，任何 cargo 命令都会失败" % member
            )

    # 只扫非注释行：块里的注释**解释**了这个坑（含 `|| true` 字样），
    # 拿全文找会误报，而误报会让人把这个门禁关掉。
    code = "\n".join(
        line for line in block.splitlines() if not line.lstrip().startswith("#")
    )
    if "|| true" in code:
        problems.append(
            "依赖层里有 `|| true`：它会把「workspace 加载失败」吞成成功，"
            "让缓存层静默失效（并掩盖真实缺陷）"
        )

    return problems


def _self_check():
    """用临时样本验证判别力：直接调用生产函数，不复制判定逻辑。"""
    import tempfile

    failures = []
    cargo = """[workspace]
members = ["crates/a", "evals"]
"""
    good_block = "\n".join(
        [
            BEGIN,
            "COPY Cargo.toml Cargo.lock ./",
            "COPY crates/a/Cargo.toml crates/a/",
            "COPY evals/Cargo.toml evals/",
            "RUN mkdir -p crates/a/src && echo \"\" > crates/a/src/lib.rs && \\",
            "    mkdir -p evals/src && echo \"\" > evals/src/lib.rs && \\",
            "    mkdir -p evals && echo \"fn main() {}\" > evals/runner.rs",
            "RUN cargo build --release -p sisyphus-bridge",
            END,
        ]
    )
    a_manifest = '[package]\nname = "a"\nversion = "0.1.0"\n'
    evals_manifest = (
        '[package]\nname = "e"\nversion = "0.1.0"\n\n[[bin]]\nname = "r"\npath = "runner.rs"\n'
    )

    def build(tc_text, block, ignore_text="target/\n"):
        td = tempfile.mkdtemp()
        os.makedirs(os.path.join(td, "crates", "a"), exist_ok=True)
        os.makedirs(os.path.join(td, "evals"), exist_ok=True)
        with open(os.path.join(td, "Cargo.toml"), "w", encoding="utf-8") as fh:
            fh.write(tc_text)
        with open(os.path.join(td, "crates", "a", "Cargo.toml"), "w", encoding="utf-8") as fh:
            fh.write(a_manifest)
        with open(os.path.join(td, "evals", "Cargo.toml"), "w", encoding="utf-8") as fh:
            fh.write(evals_manifest)
        with open(os.path.join(td, "Dockerfile"), "w", encoding="utf-8") as fh:
            fh.write("FROM scratch\n" + block + "\n")
        with open(os.path.join(td, ".dockerignore"), "w", encoding="utf-8") as fh:
            fh.write(ignore_text)
        return check(td)

    got = build(cargo, good_block)
    if got:
        failures.append("合法配置: 期望 []，实际 %r" % (got,))

    got = build(cargo, good_block.replace("COPY evals/Cargo.toml evals/\n", ""))
    if not any("evals/Cargo.toml" in g for g in got):
        failures.append("缺成员 manifest: 未检出，实际 %r" % (got,))

    got = build(cargo, good_block.replace("evals/runner.rs", "evals/other.rs"))
    if not any("runner.rs" in g for g in got):
        failures.append("缺空壳 target: 未检出，实际 %r" % (got,))

    got = build(cargo, good_block, ignore_text="target/\nevals/\n")
    if not any(".dockerignore" in g and "evals" in g for g in got):
        failures.append("成员被 .dockerignore 排除: 未检出，实际 %r" % (got,))

    got = build(cargo, good_block.replace("RUN cargo build", "RUN cargo build --release 2>/dev/null || true; cargo build"))
    if not any("|| true" in g for g in got):
        failures.append("依赖层 || true: 未检出，实际 %r" % (got,))

    if failures:
        print("❌ 自检失败：")
        for f in failures:
            print("  -", f)
        return 1
    print(f"✅ 自检通过（{5} 个判别用例）")
    return 0


def main() -> int:
    if "--self-check" in sys.argv:
        return _self_check()

    if "--fix" in sys.argv:
        members = workspace_members(".")
        block = render_block(members, stub_targets(".", members))
        with open("Dockerfile", encoding="utf-8") as fh:
            text = fh.read()
        new = replace_block(text, block)
        if new is None:
            print(
                "Dockerfile 里找不到依赖层标记，无法自动重写；请手工加入 "
                f"{BEGIN} / {END}",
                file=sys.stderr,
            )
            return 1
        with open("Dockerfile", "w", encoding="utf-8") as fh:
            fh.write(new)
        print(f"✅ 已按 workspace 重写依赖层（{len(members)} 个成员）")
        return 0

    problems = check(".")
    if problems:
        print("❌ Dockerfile / .dockerignore 与 workspace 不一致：", file=sys.stderr)
        for p in problems:
            print("  - " + p, file=sys.stderr)
        print(
            "\n这些缺陷只在**镜像内**复现（本地 cargo 一切正常）。"
            "跑 `python3 scripts/audit_dockerfile.py --fix` 重写依赖层，"
            "并确认 .dockerignore 没有排除 workspace 成员。",
            file=sys.stderr,
        )
        return 1
    print("✅ Dockerfile 依赖层与 workspace 成员一致，.dockerignore 未排除任何成员")
    return 0


if __name__ == "__main__":
    sys.exit(main())
